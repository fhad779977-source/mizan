// Shared helpers for studio scripts (Node side).
import { spawnSync, type SpawnSyncOptions } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PROJECTS_DIR = path.join(ROOT, "projects");
export const TEMPLATES_DIR = path.join(PROJECTS_DIR, "_templates");
export const PUBLIC_DIR = path.join(ROOT, "public");

export const readJson = <T = unknown>(p: string): T => JSON.parse(readFileSync(p, "utf8")) as T;
export const writeJson = (p: string, data: unknown) => writeFileSync(p, JSON.stringify(data, null, 2) + "\n");

export const args = (argv = process.argv.slice(2)) => {
  const out: Record<string, string | boolean> = {};
  const positional: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const [k, v] = a.slice(2).split("=");
      if (v !== undefined) out[k] = v;
      else if (argv[i + 1] && !argv[i + 1].startsWith("--")) out[k] = argv[++i];
      else out[k] = true;
    } else positional.push(a);
  }
  return { flags: out, positional };
};

/** Project slugs with a project.json (excluding templates). */
export const listProjects = (): string[] =>
  readdirSync(PROJECTS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_") && existsSync(path.join(PROJECTS_DIR, d.name, "project.json")))
    .map((d) => d.name)
    .sort();

export const projectPath = (slug: string) => path.join(PROJECTS_DIR, slug, "project.json");

export const run = (cmd: string, cmdArgs: string[], opts: SpawnSyncOptions = {}) => {
  const r = spawnSync(cmd, cmdArgs, { stdio: "inherit", cwd: ROOT, ...opts });
  if (r.status !== 0) throw new Error(`${cmd} ${cmdArgs.join(" ")} exited with ${r.status}`);
  return r;
};

export const capture = (cmd: string, cmdArgs: string[]) => {
  const r = spawnSync(cmd, cmdArgs, { cwd: ROOT, encoding: "utf8" });
  return { ok: r.status === 0, out: `${r.stdout ?? ""}${r.stderr ?? ""}`.trim(), status: r.status };
};

/** Composition id for a project + format, e.g. "digital-craft-vertical". */
export const compositionId = (slug: string, formatId: string) => `${slug}-${formatId}`;

/** Regenerates src/projects.generated.ts so Root registers every project. */
export const writeRegistry = () => {
  const slugs = listProjects();
  const ident = (s: string) => "p_" + s.replace(/-/g, "_");
  const lines = [
    "// AUTO-GENERATED by scripts (new-project / check). Do not edit by hand.",
    "// Lists every projects/<slug>/project.json so Root.tsx can register it.",
    ...slugs.map((s) => `import ${ident(s)} from "../projects/${s}/project.json";`),
    "",
    `export const PROJECTS: unknown[] = [${slugs.map(ident).join(", ")}];`,
    "",
  ];
  writeFileSync(path.join(ROOT, "src", "projects.generated.ts"), lines.join("\n"));
  return slugs;
};
